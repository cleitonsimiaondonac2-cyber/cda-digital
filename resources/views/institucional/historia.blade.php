<section>
  <div>
    <p>A Câmara dos Despachantes Aduaneiros de Moçambique tem uma história marcada pelo comprometimento com a profissão e com o desenvolvimento do sector aduaneiro no país. Desde os primeiros passos, em 1996, a CDA afirma-se como instituição fundamental para a regulação e promoção da actividade de despachante aduaneiro.</p>
    <ul>
      <li>
        <p>1996</p>
        <h3>Início do processo</h3>
        <p>Dá-se início ao processo de criação de uma associação de despachantes aduaneiros em Moçambique, com o objectivo de representar e defender os interesses da classe.</p>
      </li>
      <li>
        <p>2006</p>
        <h3>Retoma do processo</h3>
        <p>O processo de constituição da Câmara dos Despachantes Aduaneiros ganha novo impulso, com a mobilização dos profissionais do sector.</p>
      </li>
      <li>
        <p>2011</p>
        <h3>Criação legal</h3>
        <p>É aprovada a <strong>Lei n.º 4/2011, de 11 de Janeiro</strong>, que cria oficialmente a Câmara dos Despachantes Aduaneiros de Moçambique, reconhecendo-a como pessoa colectiva de direito público.</p>
      </li>
      <li>
        <p>16 Set 2011</p>
        <h3>Primeiros órgãos sociais</h3>
        <p>Realiza-se a Assembleia Geral Constitutiva, onde são eleitos os primeiros órgãos sociais da CDA. <strong>Gama Afonso</strong> é eleito o primeiro Presidente da Câmara.</p>
      </li>
      <li>
        <p>2012–2013</p>
        <h3>Estruturação da instituição</h3>
        <p>Primeiros anos de funcionamento da CDA, com a implementação de estruturas administrativas, criação de regulamentos internos e estabelecimento de parcerias com outras instituições.</p>
      </li>
      <li>
        <p>2014</p>
        <h3>Novo ciclo institucional</h3>
        <p>Início de um novo ciclo institucional com a eleição de <strong>Dixon Chongo</strong> para a presidência, marcando uma fase de consolidação da CDA.</p>
      </li>
      <li>
        <p>2024</p>
        <h3>Actual mandato</h3>
        <p>Eleição dos órgãos sociais para o mandato 2024-2026. <strong>Salmate Chuaibo Daud</strong> assume a presidência da CDA, com um mandato focado na modernização e digitalização dos serviços.</p>
      </li>
      <li>
        <p>2026</p>
        <h3>Portal CDA Digital</h3>
        <p>Lançamento oficial do novo portal digital da CDA, um marco na modernização dos serviços prestados aos membros e ao público.</p>
      </li>
    </ul>
